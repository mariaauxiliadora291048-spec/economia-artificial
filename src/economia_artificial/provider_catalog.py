def _provider(
    provider_id: str,
    display_name: str,
    environment_variable: str | None,
    base_url: str | None,
    api_style: str,
    embeddings: bool,
    vision: bool,
    reasoning: bool,
    tools: bool,
    streaming: bool,
    location: str,
    pricing: str,
) -> ProviderDescriptor:
    return ProviderDescriptor(
        id=provider_id,
        display_name=display_name,
        environment_variable=environment_variable,
        default_base_url=base_url,
        authentication_type="bearer" if environment_variable else "none_or_bearer",
        api_style=api_style,
        adapter="openai_compatible",
        models_endpoint="/models",
        chat_endpoint="/chat/completions",
        responses_endpoint="/responses" if api_style == "responses" else None,
        embeddings_support=embeddings,
        vision_support=vision,
        reasoning_support=reasoning,
        tool_calling_support=tools,
        streaming_support=streaming,
        local_or_cloud=location,
        pricing_model=pricing,
    )


