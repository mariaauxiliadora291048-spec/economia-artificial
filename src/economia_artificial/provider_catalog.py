def _classify(descriptor: ProviderDescriptor) -> ProviderDescriptor:
    if descriptor.id in {"openai", "huggingface"}:
        return replace(
            descriptor,
            integration_status="EXECUTABLE",
            reason="The registry has a tested OpenAI Responses transport shape for this provider.",
            models_discovery_supported=True,
            chat_supported=True,
            documentation_url=_DOCUMENTATION.get(descriptor.id),
        )
    if descriptor.id in _OPENAI_COMPATIBLE:
        return replace(
            descriptor,
            integration_status="OPENAI_COMPATIBLE",
            reason=(
                "Uses the reusable OpenAI Chat Completions adapter; credentials and endpoint "
                "remain operator-configured."
            ),
            models_discovery_supported=True,
            chat_supported=True,
            documentation_url=_DOCUMENTATION.get(descriptor.id),
        )
    if descriptor.local_or_cloud == "local" or descriptor.id == "openai_compatible":
        return replace(
            descriptor,
            integration_status="LOCAL",
            reason="Requires a discovered or manually configured local OpenAI-compatible endpoint.",
            models_discovery_supported=True,
            chat_supported=True,
            documentation_url=_DOCUMENTATION.get(descriptor.id),
        )
    if descriptor.adapter not in {"metadata", "openai_compatible"}:
        return replace(
            descriptor,
            integration_status="NATIVE_ADAPTER",
            reason=(
                "Provider has a distinct management or inference API that needs a dedicated "
                "adapter."
            ),
            required_adapter=descriptor.adapter,
            documentation_url=_DOCUMENTATION.get(descriptor.id),
        )
    return replace(
        descriptor,
        adapter="metadata",
        models_endpoint=None,
        chat_endpoint=None,
        responses_endpoint=None,
        integration_status="METADATA_ONLY",
        reason="No verified reusable adapter is included for this provider yet.",
        required_adapter="native_or_verified_openai_compatible",
        documentation_url=_DOCUMENTATION.get(descriptor.id),
    )


