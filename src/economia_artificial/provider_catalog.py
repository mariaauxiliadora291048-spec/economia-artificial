from __future__ import annotations

from dataclasses import asdict, dataclass, field, replace


@dataclass(frozen=True, slots=True)
class ProviderDescriptor:
    id: str
    display_name: str
    environment_variable: str | None
    default_base_url: str | None
    authentication_type: str
    api_style: str
    adapter: str
    models_endpoint: str | None
    chat_endpoint: str | None
    responses_endpoint: str | None
    embeddings_support: bool
    vision_support: bool
    reasoning_support: bool
    tool_calling_support: bool
    streaming_support: bool
    local_or_cloud: str
    pricing_model: str
    integration_status: str = "METADATA_ONLY"
    reason: str = "No adapter classification has been recorded."
    required_adapter: str | None = None
    models_discovery_supported: bool = False
    chat_supported: bool = False
    pricing_metadata: dict[str, object] = field(default_factory=dict)
    quota_metadata: dict[str, object] = field(default_factory=dict)
    documentation_url: str | None = None

    def public_view(self) -> dict[str, object]:
        return asdict(self)


